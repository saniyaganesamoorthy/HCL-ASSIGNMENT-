def max_product(arr):
    maximum = arr[0]
    minimum = arr[0]
    result = arr[0]

    for i in range(1, len(arr)):

        if arr[i] < 0:
            maximum, minimum = minimum, maximum

        maximum = max(arr[i], maximum * arr[i])
        minimum = min(arr[i], minimum * arr[i])

        result = max(result, maximum)

    return result


