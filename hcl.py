def longest_unique_sequence(arr):
    seen = set()
    left = 0
    max_length = 0

    for right in range(len(arr)):
        while arr[right] in seen:
            seen.remove(arr[left])
            left += 1

        seen.add(arr[right])
        max_length = max(max_length, right - left + 1)
    return max_length
arr = [1, 2, 3, 1, 4, 5]
print("Maximum length:", longest_unique_sequence(arr))

def max_subarray_sum(arr):
    current_sum = arr[0]
    max_sum = arr[0]

    for i in range(1, len(arr)):
        current_sum = max(arr[i], current_sum + arr[i])
        max_sum = max(max_sum, current_sum)

    return max_sum


arr = [-2, 3, 4, -1, 5, -6]
print("Maximum discount value:", max_subarray_sum(arr))

def trap_water(height):
    left = 0
    right = len(height) - 1

    left_max = 0
    right_max = 0
    water = 0

    while left < right:
        if height[left] < height[right]:

            if height[left] >= left_max:
                left_max = height[left]
            else:
                water += left_max - height[left]

            left += 1

        else:

            if height[right] >= right_max:
                right_max = height[right]
            else:
                water += right_max - height[right]

            right -= 1

    return water
height = [4, 2, 0, 3, 2, 5]
print("Trapped water:", trap_water(height))

def max_performance(scores):
    current = scores[0]
    maximum = scores[0]

    for i in range(1, len(scores)):
        current = max(scores[i], current + scores[i])
        maximum = max(maximum, current)

    return maximum


