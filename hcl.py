print("Number of groups:", count_subarrays(transactions, target))

def group_skills(words):
    groups = {}

    for word in words:
        key = ''.join(sorted(word))

        if key not in groups:
            groups[key] = []

        groups[key].append(word)

    return list(groups.values())


words = ["eat", "tea", "tan", "ate", "nat", "bat"]

result = group_skills(words)

print("Skill groups:")

for group in result:
    print(group)

def longest_consecutive(arr):
    numbers = set(arr)
    longest = 0

    for num in numbers:

        # Start only if num-1 does not exist
        if num - 1 not in numbers:

            current = num
            length = 1

            while current + 1 in numbers:
                current += 1
                length += 1

            longest = max(longest, length)

    return longest


packets = [100, 4, 200, 1, 3, 2]

print("Longest consecutive sequence:", longest_consecutive(packets))

def merge_intervals(intervals):

    if not intervals:
        return []

    intervals.sort()

    merged = [intervals[0]]

    for current in intervals[1:]:

        last = merged[-1]

        if current[0] <= last[1]:
            last[1] = max(last[1], current[1])

        else:
            merged.append(current)

    return merged


