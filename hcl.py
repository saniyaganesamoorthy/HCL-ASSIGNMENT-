def count_subarrays(arr, target):
    prefix_sum = 0
    count = 0

    frequency = {0: 1}

    for num in arr:
        prefix_sum += num

        if prefix_sum - target in frequency:
            count += frequency[prefix_sum - target]

        frequency[prefix_sum] = frequency.get(prefix_sum, 0) + 1

    return count


